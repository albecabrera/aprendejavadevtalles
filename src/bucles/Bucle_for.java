package bucles;

public class Bucle_for {
    public static void main(String[] args) {
        // ejemplo bucle for
        for (int i = 0 ; i <= 5; i++) {
            System.out.println("Valor = " + i); // El bucle itera mientras se cumpla, de no pasar eso, se detiene.

        }

        for (int a = 0; a < 10; a++) {
            System.out.println("El valor de a es = " + a);
        }
    }
}
